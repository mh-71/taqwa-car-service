/**
 * Close an Open follow-up. Doing it again is a 409 follow_up_closed carrying
 * currentStatus, which is how a retried click learns it already happened.
 */
async function closeFollowUp(env, id, status, note) {
  const at = nowIso();
  try {
    const row = await env.DB.prepare(
      `UPDATE follow_ups
          SET status = ?2, closed_at = ?3, close_note = ?4, updated_at = ?3
        WHERE id = ?1 AND status = '${OPEN}'
    RETURNING ${COLUMNS}`
    ).bind(id, status, at, note).first();
    if (row) return ok(toFollowUp(row));
    return explainNotOpen(env, id);
  } catch (err) {
    const mapped = constraintFailure(err);
    if (mapped) return mapped;
    console.error(`POST /api/follow-ups/:id/${status === COMPLETED ? 'complete' : 'cancel'} failed:`, err);
    return fail('database_error', 'Could not update the follow-up.', 500);
  }
}

/** POST /api/follow-ups/:id/complete — `note` optional; an empty body is fine. */
export async function completeFollowUp(request, env, rawId) {
  if (request.method !== 'POST') return methodNotAllowed(['POST']);
  if (!env.DB) return noDatabase();
  const id = readRecordId(rawId);
  if (id.error) return fail('invalid_id', id.error, 400);

  const body = await readOptionalBody(request);
  if (body.error) return fail('invalid_body', body.error, 400);
  const errors = unknownKeys(body.value, ['note']);
  const note = readText(body.value, 'note', LIMITS.closeNote);
  if (note.error) errors.note = note.error;
  if (Object.keys(errors).length) return unprocessable('Some completion fields are not valid.', errors);

  return closeFollowUp(env, id.value, COMPLETED, note.value);
}

/** POST /api/follow-ups/:id/cancel — `reason` required and kept on the record. */
