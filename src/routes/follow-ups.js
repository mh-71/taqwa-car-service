const UPDATE_FIELDS = ['vehicleId', 'reason', 'notes', 'priority', 'dueDate'];

/**
 * Merge the permitted fields into an Open follow-up. The customer is fixed;
 * the vehicle may be changed (to an active vehicle of the same customer) or
 * cleared with null. The idempotency fingerprint is never touched, so a
 * retried create still recognises its row after an edit.
 */
export async function updateFollowUp(request, env, rawId) {
  if (request.method !== 'PUT') return methodNotAllowed(['PUT']);
  if (!env.DB) return noDatabase();

  const id = readRecordId(rawId);
  if (id.error) return fail('invalid_id', id.error, 400);

  const body = await readJsonBody(request);
  if (body.error) return fail('invalid_body', body.error, 400);
  const b = body.value;

  const errors = unknownKeys(b, UPDATE_FIELDS);
  if (b.customerId !== undefined) {
    errors.customerId = '`customerId` cannot be changed. Create a new follow-up for another customer.';
  }
  if (b.idempotencyKey !== undefined) {
    errors.idempotencyKey = '`idempotencyKey` is only used when creating a follow-up.';
  }
  const values = {};
  if (b.vehicleId !== undefined) {
    const v = readOptionalId(b, 'vehicleId');
    if (v.error) errors.vehicleId = v.error; else values.vehicle_id = v.value;
  }
  if (b.reason !== undefined) {
    const v = readString(b, 'reason', { required: true, max: LIMITS.reason });
    if (v.error) errors.reason = v.error; else values.reason = v.value;
  }
  if (b.notes !== undefined) {
    const v = readText(b, 'notes', LIMITS.notes);
    if (v.error) errors.notes = v.error; else values.notes = v.value;
  }
  if (b.priority !== undefined) {
    const v = readEnum(b, 'priority', PRIORITIES, { required: true });
    if (v.error) errors.priority = v.error; else values.priority = v.value;
  }
  if (b.dueDate !== undefined) {
    const v = readDate(b, 'dueDate', { required: true });
    if (v.error) errors.dueDate = v.error; else values.due_date = v.value;
  }

  if (Object.keys(errors).length) {
    return unprocessable('Some follow-up fields are not valid.', errors);
  }
  const names = Object.keys(values);
  if (!names.length) return unprocessable('No follow-up fields were supplied to update.');

  const at = nowIso();
  const assignments = names.map((n, i) => `${n} = ?${i + 1}`);
  const binds = names.map((n) => values[n]);
  const pAt = binds.push(at);
  const pId = binds.push(id.value);
  assignments.push(`updated_at = ?${pAt}`);

  // A changed vehicle must be an active vehicle of this follow-up's own
  // customer; keeping the current one needs no re-check.
  let vehicleGuard = '';
  if ('vehicle_id' in values && values.vehicle_id !== null) {
    const pV = binds.push(values.vehicle_id);
    vehicleGuard = `AND (?${pV} IS follow_ups.vehicle_id
                         OR EXISTS (SELECT 1 FROM vehicles
                                     WHERE id = ?${pV} AND customer_id = follow_ups.customer_id
                                       AND status = '${ACTIVE}'))`;
  }

  try {
    const row = await env.DB.prepare(
      `UPDATE follow_ups
          SET ${assignments.join(', ')}
        WHERE id = ?${pId} AND status = '${OPEN}'
          ${vehicleGuard}
    RETURNING ${COLUMNS}`
    ).bind(...binds).first();

    if (row) return ok(toFollowUp(row));

    const current = await readFollowUpRow(env, id.value);
    if (!current) return fail('not_found', 'No follow-up with that id.', 404);
    if (current.status !== OPEN) return closedConflict(current);
    if ('vehicle_id' in values && values.vehicle_id !== null) {
      const refusal = await explainPartyRefusal(env, current.customer_id, values.vehicle_id, current.vehicle_id);
      if (refusal) return refusal;
    }
    return conflict('This follow-up was changed by another request. Reload it and try again.',
      { reason: 'concurrent_modification' });
  } catch (err) {
    const mapped = constraintFailure(err);
    if (mapped) return mapped;
    console.error('PUT /api/follow-ups/:id failed:', err);
    return fail('database_error', 'Could not update the follow-up.', 500);
  }
}

