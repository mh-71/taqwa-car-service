/* ============================================================
   routes/follow-ups.js — Customer CRM › Customer Follow-up (0005)
   ------------------------------------------------------------
   GET  /api/follow-ups[/:id]
   POST /api/follow-ups
   PUT  /api/follow-ups/:id
   POST /api/follow-ups/:id/complete
   POST /api/follow-ups/:id/cancel
   POST /api/follow-ups/:id/contact

   A follow-up is a task -- call this customer, optionally about one
   of their vehicles, about something, by a due date. Its contact
   attempts live in follow_up_contacts (routes/follow-up-contacts.js),
   which is append-only.

   ---- the rules this route owns ----

   1. STRICT FIELDS. Every write names the keys it accepts; any other
      key is a 422, so a caller can never believe it set a status, a
      timestamp, an id or the contact cache.

   2. ONE SUBMISSION, ONE ROW. Creating a follow-up and recording a
      contact each require `idempotencyKey`, generated by the client
      once per intentional submission and reused unchanged on a retry.
      The key is UNIQUE in its table and the row also stores a SHA-256
      fingerprint of the normalised payload, taken at creation and never
      changed. So:
        same key + same payload  -> 200, replayed: true, the same record
        same key + other payload -> 409 idempotency_key_reused
        new key                  -> a new record, even if identical
      Nothing here compares content or time to guess at duplicates:
      several Open follow-ups for the same customer, vehicle and reason
      are allowed, and so are two identical contacts.

   3. THE CHECKS ARE PART OF THE WRITE. Customer and vehicle status and
      ownership are in the INSERT's own WHERE; "the follow-up is Open"
      is in every UPDATE's WHERE. A request that loses a race simply
      matches nothing, and only then is the refusal explained.

   4. ONE BATCH. A contact, the follow-up's last_contact_at/last_outcome
      (recomputed from the Active contacts, never taken from a request)
      and the due date it may move are written together, the cache
      update conditional on the contact having been inserted.

   5. CLOSED IS FINAL. Completed and Cancelled follow-ups are never
      reopened, edited or given new contacts. Their contacts can still
      be voided, which only recomputes the cache.
   ============================================================ */

