const CONTACT_FIELDS = ['outcome', 'note', 'nextContactDate', 'recordedBy', 'idempotencyKey'];

/**
 * The response for a contact: the follow-up as it is now in `data` (that is
 * what Storage.action caches under follow-ups) and the contact in `contact`.
 */
async function respondWithContact(env, contactId, status, extra = {}) {
  const contact = await env.DB.prepare(
    `SELECT ${CONTACT_COLUMNS} FROM follow_up_contacts WHERE id = ?1 LIMIT 1`
  ).bind(contactId).first();
  const followUp = contact ? await readFollowUpRow(env, contact.follow_up_id) : null;
  if (!contact || !followUp) {
    console.error(`Follow-up contact ${contactId} could not be read back.`);
    return fail('database_error', 'Could not read the contact back.', 500);
  }
  return ok(toFollowUp(followUp), { contact: toContact(contact), ...extra }, status);
}

/** The stored replay of a contact, or the refusal for a reused key; null if the key is new. */
async function replayContact(env, key, fp) {
  const row = await env.DB.prepare(
    `SELECT id, idempotency_fingerprint FROM follow_up_contacts WHERE idempotency_key = ?1 LIMIT 1`
  ).bind(key).first();
  if (!row) return null;
  if (row.idempotency_fingerprint !== fp) {
    return conflict('This submission key was already used for a different contact. Start a new submission.',
      { reason: 'idempotency_key_reused' });
  }
  return respondWithContact(env, row.id, 200, { replayed: true });
}

export async function recordContact(request, env, rawId) {
  if (request.method !== 'POST') return methodNotAllowed(['POST']);
  if (!env.DB) return noDatabase();

  const id = readRecordId(rawId);
  if (id.error) return fail('invalid_id', id.error, 400);

  const body = await readJsonBody(request);
  if (body.error) return fail('invalid_body', body.error, 400);
  const b = body.value;

  const errors = unknownKeys(b, CONTACT_FIELDS);
  const outcome = readEnum(b, 'outcome', OUTCOMES, { required: true });
  if (outcome.error) errors.outcome = outcome.error;
  const note = readText(b, 'note', LIMITS.note);
  if (note.error) errors.note = note.error;
  else if (outcome.value === 'other' && note.value === null) {
    errors.note = 'A note is required when the outcome is "other".';
  }
  const next = readDate(b, 'nextContactDate');
  if (next.error) errors.nextContactDate = next.error;
  else if (outcome.value === 'callback_requested' && !next.value) {
    errors.nextContactDate = 'A next contact date is required when a callback is requested.';
  }
  const recordedBy = readText(b, 'recordedBy', LIMITS.name);
  if (recordedBy.error) errors.recordedBy = recordedBy.error;
  const key = readIdempotencyKey(b);
  if (key.error) errors.idempotencyKey = key.error;

  if (Object.keys(errors).length) {
    return unprocessable('Some contact fields are not valid.', errors);
  }
  const nextDate = next.value || null;

  const fp = await fingerprint([
    'follow_up.contact.v1', id.value, outcome.value, note.value, nextDate, recordedBy.value,
  ]);

  try {
    // As with a create: a retry finds what it already recorded, even if the
    // follow-up has been closed since.
    const replay = await replayContact(env, key.value, fp);
    if (replay) return replay;

    const allocated = await allocateId(env, 'followUpContacts');
    if (allocated.error) {
      console.error('POST /api/follow-ups/:id/contact could not allocate an id:', allocated.error);
      return fail('database_error', 'Could not record the contact.', 500);
    }
    const at = nowIso();

    // ?1 contact id ?2 follow-up ?3 now ?4 outcome ?5 note ?6 next date
    // ?7 recorded_by ?8 key ?9 fingerprint
    const results = await env.DB.batch([
      env.DB.prepare(
        `INSERT INTO follow_up_contacts
           (id, follow_up_id, contacted_at, outcome, note, next_contact_date, recorded_by,
            status, idempotency_key, idempotency_fingerprint, created_at)
         SELECT ?1, ?2, ?3, ?4, ?5, ?6, ?7, '${ACTIVE}', ?8, ?9, ?3
          WHERE EXISTS (SELECT 1 FROM follow_ups WHERE id = ?2 AND status = '${OPEN}')
         ON CONFLICT(idempotency_key) DO NOTHING`
      ).bind(
        allocated.id, id.value, at, outcome.value, note.value, nextDate, recordedBy.value,
        key.value, fp,
      ),
      // Conditional on THIS request's contact existing, so a refused or
      // raced insert moves nothing.
      env.DB.prepare(
        `UPDATE follow_ups
            SET last_contact_at = ${LATEST_ACTIVE('contacted_at')},
                last_outcome    = ${LATEST_ACTIVE('outcome')},
                due_date        = COALESCE(?3, due_date),
                updated_at      = ?2
          WHERE id = ?1 AND status = '${OPEN}'
            AND EXISTS (SELECT 1 FROM follow_up_contacts WHERE id = ?4)`
      ).bind(id.value, at, nextDate, allocated.id),
    ]);

    if ((results[0]?.meta?.changes ?? 0) !== 1) {
      const raced = await replayContact(env, key.value, fp);
      if (raced) return raced;
      return explainNotOpen(env, id.value);
    }
    if ((results[1]?.meta?.changes ?? 0) !== 1) {
      // Cannot happen inside one transaction; reported rather than hidden.
      console.error(`Contact ${allocated.id} was recorded but its follow-up was not updated.`);
    }
    return respondWithContact(env, allocated.id, 201);
  } catch (err) {
    const mapped = constraintFailure(err);
    if (mapped) return mapped;
    console.error('POST /api/follow-ups/:id/contact failed:', err);
    return fail('database_error', 'Could not record the contact.', 500);
  }
}
