/**
 * Keys the server owns, refused by name with a reason rather than with the
 * generic "not accepted", so a caller learns where the value comes from.
 */
const SERVER_OWNED = {
  id: '`id` is allocated by the server.',
  status: '`status` is set by the server. Use the complete or cancel operation.',
  lastContactAt: '`lastContactAt` is calculated from the contact history.',
  lastOutcome: '`lastOutcome` is calculated from the contact history.',
  closedAt: '`closedAt` is set by the complete or cancel operation.',
  closeNote: '`closeNote` is set by the complete or cancel operation.',
  contactedAt: '`contactedAt` is the server time when the contact is recorded.',
  createdAt: '`createdAt` is set by the server.',
  updatedAt: '`updatedAt` is set by the server.',
  idempotencyFingerprint: '`idempotencyFingerprint` is calculated by the server.',
};

/** 422 messages for every key of `body` that `allowed` does not list. */
export function unknownKeys(body, allowed) {
  const errors = {};
  for (const key of Object.keys(body)) {
    if (!allowed.includes(key)) {
      errors[key] = SERVER_OWNED[key] || `\`${key}\` is not accepted here.`;
    }
  }
  return errors;
}

/** The client's once-per-submission key. Required wherever it is allowed. */
export function readIdempotencyKey(body) {
  const raw = body.idempotencyKey;
  if (raw === undefined || raw === null || raw === '') {
    return { error: '`idempotencyKey` is required: one new key per submission, reused only to retry it.' };
  }
  if (typeof raw !== 'string' || !KEY_SHAPE.test(raw)) {
    return { error: '`idempotencyKey` must be 16 to 64 letters, digits or hyphens.' };
  }
  return { value: raw };
}

/**
 * SHA-256 (lowercase hex) of the normalised payload. The input is a JSON
 * ARRAY in a fixed order, so key order in the request cannot change it, and
 * starts with a versioned label naming the operation, so a create payload
 * can never match a contact payload.
 */
export async function fingerprint(parts) {
  const bytes = new TextEncoder().encode(JSON.stringify(parts));
  const digest = await crypto.subtle.digest('SHA-256', bytes);
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

/** An optional record id in a body field: '' / null -> null. */
function readOptionalId(body, field) {
  const raw = body[field];
  if (raw === undefined || raw === null || raw === '') return { value: null };
  if (typeof raw !== 'string') return { error: `\`${field}\` must be a record id or null.` };
  const id = readRecordId(raw.trim());
  return id.error ? { error: `\`${field}\`: ${id.error}` } : { value: id.value };
}

/** Optional text: trimmed, '' stored as NULL. */
function readText(body, field, max) {
  const r = readString(body, field, { max });
  return r.error ? r : { value: r.value === '' ? null : r.value };
}

/**
 * The latest Active contact of the follow-up row being updated, as two
 * correlated subqueries. contacted_at is server-set ISO text, so text order is
 * time order; rowid breaks a same-millisecond tie deterministically (text ids
 * would mis-sort past FUC-9999). A Void contact never counts.
 */
export const LATEST_ACTIVE = (col) => `(
  SELECT c.${col} FROM follow_up_contacts c
   WHERE c.follow_up_id = follow_ups.id AND c.status = '${ACTIVE}'
   ORDER BY c.contacted_at DESC, c.rowid DESC
   LIMIT 1)`;

async function readFollowUpRow(env, id) {
  return env.DB.prepare(`SELECT ${COLUMNS} FROM follow_ups WHERE id = ?1 LIMIT 1`).bind(id).first();
}

const closedConflict = (row) => conflict(
  `This follow-up is already ${row.status}. A closed follow-up cannot be changed; create a new one if more work is needed.`,
  { reason: 'follow_up_closed', currentStatus: row.status },
);

/** Why a guarded follow-up UPDATE matched nothing. */
async function explainNotOpen(env, id) {
  const row = await readFollowUpRow(env, id);
  if (!row) return fail('not_found', 'No follow-up with that id.', 404);
  if (row.status !== OPEN) return closedConflict(row);
  return conflict('This follow-up was changed by another request. Reload it and try again.',
    { reason: 'concurrent_modification' });
}

/**
 * Why a customer/vehicle pair cannot take a follow-up, or null if it can.
 * `currentVehicleId`: on an update, the vehicle already on the follow-up,
 * which is accepted as it is (it was checked when it was set).
 */
async function explainPartyRefusal(env, customerId, vehicleId, currentVehicleId = null) {
  const row = await env.DB.prepare(
    `SELECT (SELECT status FROM customers WHERE id = ?1)     AS customer_status,
            (SELECT customer_id FROM vehicles WHERE id = ?2) AS vehicle_owner,
            (SELECT status FROM vehicles WHERE id = ?2)      AS vehicle_status`
  ).bind(customerId, vehicleId).first();
  if (!row || row.customer_status === null) {
    return conflict('That customer does not exist.', { reason: 'customer_not_found' });
  }
  if (row.customer_status !== ACTIVE) {
    return conflict('That customer is Inactive. Reactivate the customer before creating a follow-up.',
      { reason: 'customer_inactive' });
  }
  if (vehicleId === null || vehicleId === currentVehicleId) return null;
  if (row.vehicle_owner === null) {
    return conflict('That vehicle does not exist.', { reason: 'vehicle_not_found' });
  }
  if (row.vehicle_owner !== customerId) {
    return unprocessable('Some follow-up fields are not valid.', {
      vehicleId: 'Selected vehicle does not belong to this customer.',
    });
  }
  if (row.vehicle_status !== ACTIVE) {
    return conflict('That vehicle is Inactive. Choose an active vehicle or none.',
      { reason: 'vehicle_inactive' });
  }
  return null;
}

